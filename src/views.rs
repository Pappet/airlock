//! Generated Markdown views of a snapshot: `PLAN.md` and `QUESTIONS.md` (Spec 05 §3.1, §4).
//!
//! Views are rendered from the [`Snapshot`], not from live state, so they are
//! deterministic and session activity (claims, leases) never changes them.

use crate::core::{Question, TaskState, TaskStatus};
use crate::snapshot::{Snapshot, TaskRecord};
use std::collections::{BTreeMap, HashSet};
use std::fmt::Write;

const HEADER: &str = "<!-- Generated by `airlock sync`. Do not edit: changes are overwritten. \
                      On a merge conflict, take either side and re-run `airlock sync`. -->\n\n";

/// Renders the plan view: a per-role summary followed by every work package.
pub fn plan(snapshot: &Snapshot) -> String {
    let done: HashSet<&str> = snapshot
        .tasks
        .iter()
        .filter(|t| t.state == TaskState::Done)
        .map(|t| t.id.as_str())
        .collect();
    let mut by_role: BTreeMap<&str, Vec<(&TaskRecord, TaskStatus)>> = BTreeMap::new();
    for task in &snapshot.tasks {
        by_role
            .entry(&task.role)
            .or_default()
            .push((task, status(task, &done)));
    }

    let mut out = format!("{HEADER}# Plan\n");
    if by_role.is_empty() {
        out.push_str("\n_No tasks._\n");
        return out;
    }

    out.push_str(
        "\n| Role | Blocked | Ready | In review | Done |\n| --- | ---: | ---: | ---: | ---: |\n",
    );
    for (role, tasks) in &by_role {
        let count = |s: TaskStatus| tasks.iter().filter(|(_, status)| *status == s).count();
        let _ = writeln!(
            out,
            "| {} | {} | {} | {} | {} |",
            inline(role).replace('|', "\\|"),
            count(TaskStatus::Blocked),
            count(TaskStatus::Ready),
            count(TaskStatus::InReview),
            count(TaskStatus::Done)
        );
    }

    for (role, tasks) in &by_role {
        let _ = write!(out, "\n## {}\n", inline(role));
        for (task, status) in tasks {
            let _ = write!(
                out,
                "\n### {} — {}\n\n",
                inline(&task.id),
                inline(&task.title)
            );
            let _ = write!(out, "- **Status:** {}", status.as_str());
            if let Some(track) = &task.track {
                let _ = write!(out, " · **Track:** {}", inline(track));
            }
            let _ = writeln!(out, " · **Priority:** {}", task.priority.as_str());
            if !task.blocked_by.is_empty() {
                let _ = writeln!(out, "- **Blocked by:** {}", task.blocked_by.join(", "));
            }
            if !task.read.is_empty() {
                let _ = writeln!(out, "- **Read:** {}", code_list(&task.read));
            }
            if !task.touch.is_empty() {
                let _ = writeln!(out, "- **Touch:** {}", code_list(&task.touch));
            }
            let _ = writeln!(out, "- **Do:** {}", item_text(&task.r#do));
            let _ = writeln!(out, "- **Verify:** {}", item_text(&task.verify));
            if let Some(notes) = &task.notes {
                let _ = writeln!(out, "- **Notes:** {}", item_text(notes));
            }
        }
    }
    out
}

/// Renders the question log, grouped by topic: the clean-room audit trail.
pub fn questions(snapshot: &Snapshot) -> String {
    let mut by_topic: BTreeMap<&str, Vec<&Question>> = BTreeMap::new();
    for question in &snapshot.questions {
        by_topic.entry(&question.topic).or_default().push(question);
    }

    let mut out = format!(
        "{HEADER}# Airlock Questions\n\nBehavioral questions and answers exchanged across the airlock.\n"
    );
    if by_topic.is_empty() {
        out.push_str("\n_No questions._\n");
        return out;
    }

    for (topic, questions) in &by_topic {
        let _ = write!(out, "\n## {}\n", inline(topic));
        for q in questions {
            let _ = write!(out, "\n### #{} · {}\n\n", q.id, q.status.as_str());
            let _ = writeln!(out, "- **Asked by:** {}", inline(&q.asked_by));
            let _ = writeln!(out, "- **Question:** {}", item_text(&q.question));
            if let Some(answer) = &q.answer {
                let by = inline(q.answered_by.as_deref().unwrap_or("unknown"));
                let _ = writeln!(out, "- **Answer** ({by}): {}", item_text(answer));
            }
            if let Some(at) = q.corrected_at {
                let by = inline(q.corrected_by.as_deref().unwrap_or("unknown"));
                let _ = writeln!(out, "- **Corrected** ({by}, {})", utc_date(at));
            }
            for earlier in q.history.iter().rev() {
                let by = inline(earlier.answered_by.as_deref().unwrap_or("unknown"));
                let _ = writeln!(
                    out,
                    "- **Earlier answer** ({by}): {}",
                    item_text(&earlier.answer)
                );
            }
            if let Some(spec) = &q.spec_file {
                let _ = writeln!(out, "- **Codified in:** {}", code(spec));
            }
        }
    }
    out
}

/// `YYYY-MM-DD HH:MM` of a unix timestamp in UTC.
pub(crate) fn utc_minute(unix_secs: i64) -> String {
    let minute_of_day = unix_secs.rem_euclid(86_400) / 60;
    format!(
        "{} {:02}:{:02}",
        utc_date(unix_secs),
        minute_of_day / 60,
        minute_of_day % 60
    )
}

/// `YYYY-MM-DD` of a unix timestamp in UTC (proleptic Gregorian calendar).
fn utc_date(unix_secs: i64) -> String {
    let days = unix_secs.div_euclid(86_400) + 719_468;
    let era = days.div_euclid(146_097);
    let day_of_era = days.rem_euclid(146_097);
    let year_of_era =
        (day_of_era - day_of_era / 1_460 + day_of_era / 36_524 - day_of_era / 146_096) / 365;
    let day_of_year = day_of_era - (365 * year_of_era + year_of_era / 4 - year_of_era / 100);
    let shifted_month = (5 * day_of_year + 2) / 153;
    let day = day_of_year - (153 * shifted_month + 2) / 5 + 1;
    let month = if shifted_month < 10 {
        shifted_month + 3
    } else {
        shifted_month - 9
    };
    let year = year_of_era + era * 400 + i64::from(month <= 2);
    format!("{year:04}-{month:02}-{day:02}")
}

fn status(task: &TaskRecord, done: &HashSet<&str>) -> TaskStatus {
    match task.state {
        TaskState::Open | TaskState::InProgress => {
            if task.blocked_by.iter().all(|id| done.contains(id.as_str())) {
                TaskStatus::Ready
            } else {
                TaskStatus::Blocked
            }
        }
        TaskState::InReview => TaskStatus::InReview,
        TaskState::Done => TaskStatus::Done,
    }
}

/// Text that must stay on one line (headings, table cells, names): all
/// whitespace runs, including newlines, collapse to a single space.
fn inline(text: &str) -> String {
    text.split_whitespace().collect::<Vec<_>>().join(" ")
}

/// Text inside a list item: continuation lines are indented to stay in the item.
fn item_text(text: &str) -> String {
    text.trim_end().replace('\n', "\n  ")
}

fn code(text: &str) -> String {
    if text.contains('`') {
        text.to_string()
    } else {
        format!("`{text}`")
    }
}

fn code_list(items: &[String]) -> String {
    items.iter().map(|i| code(i)).collect::<Vec<_>>().join(", ")
}
